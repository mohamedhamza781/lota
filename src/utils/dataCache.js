// كاش بسيط بالذاكرة (مش localStorage) لبيانات الصفحات - بيحل مشكلة إنه
// كل ما تنتقل لتاب/صفحة تانية وترجع للي قبلها، الصفحة تعيد تحميل/تجيب
// البيانات من الصفر، رغم إنها جابتها قبل شوي وما تغيّر شي حقيقي.
//
// السبب الأصلي: React Router بيفكّك (unmount) الصفحة القديمة بالكامل لما
// تنتقل لصفحة تانية، وبيركّبها (mount) من جديد لما ترجعلها - فأي
// useEffect لجلب البيانات بيشتغل من الصفر كل مرة.
//
// الحل هون: كاش بالذاكرة (يعيش طول ما التطبيق مفتوح بنفس تبويب المتصفح،
// وينمسح تلقائياً لو عملت ريفرش كامل للصفحة) - أول ما توصل بيانات لأي
// مفتاح، منخزنها، وبعدها أي صفحة ترجع تسأل عن نفس المفتاح بتاخده فوراً
// بدل ما تستنى طلب شبكة جديد.
//
// نمط الاستخدام الموصى فيه (stale-while-revalidate): اعرض القيمة
// المخزّنة فوراً (لو موجودة) بدون انتظار، وبنفس الوقت اطلب نسخة جديدة
// بالخلفية وحدّث الكاش والعرض لما توصل - هيك المستخدم ما بيشوف "تحميل"
// فاضي أبداً، وبرضو البيانات بتضل محدّثة.

const cache = new Map();

export function getCached(key) {
  return cache.has(key) ? cache.get(key) : undefined;
}

export function setCached(key, value) {
  cache.set(key, value);
}

export function clearCached(key) {
  if (key) cache.delete(key);
  else cache.clear();
}